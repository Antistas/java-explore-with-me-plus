-- Создание таблицы hits
CREATE TABLE IF NOT EXISTS hits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app VARCHAR(255) NOT NULL,
    uri VARCHAR(255) NOT NULL,
    ip VARCHAR(255) NOT NULL,
    hit_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_hit_timestamp ON hits(hit_timestamp);
CREATE INDEX IF NOT EXISTS idx_uri ON hits(uri);
CREATE INDEX IF NOT EXISTS idx_ip ON hits(ip);